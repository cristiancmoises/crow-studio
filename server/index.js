import {createApp} from './app.js';
import {generateDesign as generateWithCli} from './qwen.js';
import {generateDesign as generateLocally} from './ollama.js';
import packageInfo from '../package.json' with {type:'json'};
const provider=process.env.AI_PROVIDER||'qwen-code';
if(!['ollama','qwen-code'].includes(provider))throw new Error('AI_PROVIDER deve ser ollama ou qwen-code.');
const local=provider==='ollama';
const app=createApp({generateDesign:local?generateLocally:generateWithCli,trustedProxyIps:process.env.TRUSTED_PROXY_IPS||'',aiConfig:{provider,apiKey:process.env.OPENAI_API_KEY,baseUrl:local?(process.env.OLLAMA_BASE_URL||'http://inference:11434'):process.env.OPENAI_BASE_URL,model:local?(process.env.OLLAMA_MODEL||'qwen3:1.7b'):process.env.OPENAI_MODEL,timeoutMs:Number(process.env.AI_TIMEOUT_MS||(local?85000:120000))}});
const port=Number(process.env.PORT||8080);
app.server.listen(port,process.env.HOST||'0.0.0.0',()=>console.log(`Crow Studio ${packageInfo.version} · http://localhost:${app.server.address().port}`));
for(const signal of ['SIGTERM','SIGINT'])process.on(signal,async()=>{await app.close();process.exit(0);});
