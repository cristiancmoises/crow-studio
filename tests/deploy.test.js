import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,copyFile,writeFile,readFile,stat,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
test('bootstrap generates private credentials and preserves existing configuration',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'crow-bootstrap-'));
  t.after(()=>rm(dir,{recursive:true,force:true}));
  await mkdir(join(dir,'scripts'));await mkdir(join(dir,'bin'));
  await copyFile('scripts/start.sh',join(dir,'scripts/start.sh'));
  await writeFile(join(dir,'scripts/provision-model.sh'),'#!/bin/sh\nprintf "model-cache-checked\\n" >> "$CALLS_FILE"\n');
  await writeFile(join(dir,'bin/docker'),'#!/bin/sh\nprintf "%s\\n" "$*" >> "$CALLS_FILE"\n',{mode:0o700});
  const env={...process.env,AI_PROVIDER:'',PATH:join(dir,'bin')+':'+process.env.PATH,CALLS_FILE:join(dir,'calls')};
  const output=execFileSync('sh',[join(dir,'scripts/start.sh')],{env,encoding:'utf8'});
  const before=await readFile(join(dir,'.env'),'utf8');
  assert.ok(/STUDIO_PASSWORD=[a-f0-9]{48}/.test(before));assert.ok(/SESSION_SECRET=[a-f0-9]{64}/.test(before));
  assert.equal((await stat(join(dir,'.env'))).mode&0o777,0o600);
  const password=before.match(/^STUDIO_PASSWORD=(.*)$/m)[1];
  assert.ok(output.includes('Credenciais gravadas em .env'));assert.ok(!output.includes(password));
  const again=execFileSync('sh',[join(dir,'scripts/start.sh')],{env,encoding:'utf8'});
  assert.ok(await readFile(join(dir,'.env'),'utf8')===before,'Existing configuration must remain unchanged');assert.ok(!again.includes(password));
  const calls=await readFile(join(dir,'calls'),'utf8');
  assert.match(calls,/compose up -d --build/);assert.equal(calls.split('\n').filter(line=>line==='model-cache-checked').length,2);
});
